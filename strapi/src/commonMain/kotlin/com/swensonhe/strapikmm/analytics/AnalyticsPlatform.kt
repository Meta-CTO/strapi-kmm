package com.swensonhe.strapikmm.analytics

/**
 * The [AnalyticsPlatform] enum represents various analytics platforms that can be used for tracking events.
 */
enum class AnalyticsPlatform {
    /**
     * Amplitude: An analytics platform that provides user behavior insights and event tracking.
     */
    AMPLITUDE,

    /**
     * CleverTap: An analytics and engagement platform for creating personalized user experiences.
     */
    CLEVERTAP
}